# frozen_string_literal: true

class BibleTerminology < ApplicationRecord
  # ---------------------------------------------------------------------------
  # Concerns
  # ---------------------------------------------------------------------------
  include Embeddable
  include BibleDocSynced

  # ---------------------------------------------------------------------------
  # Associations
  # ---------------------------------------------------------------------------
  belongs_to :novel

  # ---------------------------------------------------------------------------
  # Callbacks
  # ---------------------------------------------------------------------------
  before_save :set_last_updated_at

  # ---------------------------------------------------------------------------
  # Validations
  # ---------------------------------------------------------------------------
  validates :term, presence: true

  # ---------------------------------------------------------------------------
  # Scopes
  # ---------------------------------------------------------------------------
  scope :by_term, -> { order(:term) }

  # ---------------------------------------------------------------------------
  # Embeddable implementation
  # ---------------------------------------------------------------------------
  def embeddable_text
    [
      term,
      korean_term,
      definition,
      usage_notes,
      notes
    ].compact.reject(&:blank?).join(" ")
  end

  # ---------------------------------------------------------------------------
  # BibleDocSynced implementation
  # ---------------------------------------------------------------------------
  def bible_doc_category
    :terminology
  end

  private

  def set_last_updated_at
    self.last_updated_at = Time.current
  end
end

class Membership < ApplicationRecord
  # ---------------------------------------------------------------------------
  # Associations
  # ---------------------------------------------------------------------------
  belongs_to :user
  belongs_to :team

  # ---------------------------------------------------------------------------
  # Enums
  # ---------------------------------------------------------------------------
  enum :role, { team_admin: "team_admin", team_member: "team_member" }

  # ---------------------------------------------------------------------------
  # Validations
  # ---------------------------------------------------------------------------
  validates :role,    presence: true
  validates :user_id, uniqueness: { scope: :team_id }
end
